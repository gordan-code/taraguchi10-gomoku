import { describe, expect, it } from 'vitest'
import { Board, Color, Pos, idx } from '../types'
import { emptyBoard } from '../board'
import { checkForbidden } from '../forbidden'

/** 直接摆子构造棋盘（禁手测试需要非交替落子的自由摆位） */
function forbiddenAt(stones: Array<[number, number, Color]>) {
  const b = emptyBoard()
  let last: Pos = { x: 7, y: 7 }
  for (const [x, y, c] of stones) {
    b[idx(x, y)] = c
    last = { x, y }
  }
  return checkForbidden(b as Board, last)
}

describe('禁手判定：长连与五连优先', () => {
  it('黑方连成 7 子为长连禁手', () => {
    // 行 7：x=4,5,6,8,9,10 已有黑，p=(7,7) → 4..10 七连
    expect(
      forbiddenAt([
        [4, 7, 1], [5, 7, 1], [6, 7, 1], [8, 7, 1], [9, 7, 1], [10, 7, 1],
        [7, 7, 1]
      ])
    ).toBe('overline')
  })

  it('同线长连（其中含五连）仍为长连禁手', () => {
    // 行 7：x=4..8 已有黑 5 颗中的 4 颗 + 两端延伸？构造纯长连：
    // x=3,4,5,6,8,9 + p=(7,7) → 3..9 七连（同线，非"恰好五连"）
    expect(
      forbiddenAt([
        [3, 7, 1], [4, 7, 1], [5, 7, 1], [6, 7, 1], [8, 7, 1], [9, 7, 1],
        [7, 7, 1]
      ])
    ).toBe('overline')
  })

  it('恰好五连 + 同手另一方向形成活三 → 五连优先，不算禁手', () => {
    // 行 7：x=4,5,6,8 已有黑，p=(7,7) → 恰好五连（4..8）
    // 纵向：(7,5)(7,6)+p → 活三
    expect(
      forbiddenAt([
        [4, 7, 1], [5, 7, 1], [6, 7, 1], [8, 7, 1],
        [7, 5, 1], [7, 6, 1],
        [7, 7, 1]
      ])
    ).toBeNull()
  })

  it('恰好五连 + 同手另一方向形成长连 → 五连优先，不算禁手', () => {
    // 纵向 5..9 恰好五连；横向 4..10 七连长连 → 裁决：五连优先
    expect(
      forbiddenAt([
        [7, 5, 1], [7, 6, 1], [7, 8, 1], [7, 9, 1],
        [4, 7, 1], [5, 7, 1], [6, 7, 1], [8, 7, 1], [9, 7, 1], [10, 7, 1],
        [7, 7, 1]
      ])
    ).toBeNull()
  })
})

describe('禁手判定：四四', () => {
  it('两方向各成一个四 → 四四禁手', () => {
    expect(
      forbiddenAt([
        [4, 7, 1], [5, 7, 1], [6, 7, 1],
        [7, 4, 1], [7, 5, 1], [7, 6, 1],
        [7, 7, 1]
      ])
    ).toBe('double-four')
  })

  it('同一线上两个四（X_XXX_X 型）→ 四四禁手', () => {
    // 行 7：4B,5_,6B,7B(p),8B,9_,10B
    expect(
      forbiddenAt([
        [4, 7, 1], [6, 7, 1], [8, 7, 1], [10, 7, 1],
        [7, 7, 1]
      ])
    ).toBe('double-four')
  })

  it('活四只计为一个四（不构成四四）', () => {
    // 行 7：5B,6B,7B(p),8B 恰四连，两端空 → 一个活四
    expect(
      forbiddenAt([
        [5, 7, 1], [6, 7, 1], [8, 7, 1],
        [7, 7, 1]
      ])
    ).toBeNull()
  })

  it('活四（一方向）+ 活三（另一方向）不为禁手', () => {
    expect(
      forbiddenAt([
        [5, 7, 1], [6, 7, 1], [8, 7, 1],
        [7, 5, 1], [7, 6, 1],
        [7, 7, 1]
      ])
    ).toBeNull()
  })

  it('冲四被白棋挡住一端仍是四（两方向冲四 → 四四）', () => {
    // 白 (3,7) 挡住横向左端；纵向再叠一个四
    expect(
      forbiddenAt([
        [3, 7, 2], [4, 7, 1], [5, 7, 1], [6, 7, 1],
        [7, 4, 1], [7, 5, 1], [7, 6, 1],
        [7, 7, 1]
      ])
    ).toBe('double-four')
  })
})

describe('禁手判定：三三', () => {
  it('两方向各成活三 → 三三禁手', () => {
    expect(
      forbiddenAt([
        [5, 7, 1], [6, 7, 1],
        [7, 5, 1], [7, 6, 1],
        [7, 7, 1]
      ])
    ).toBe('double-three')
  })

  it('成三后另一方向连三 → 三三禁手（p 补中间）', () => {
    // 横向 (5,7)(7,7) + p=(6,7)；纵向 (6,5)(6,6) + p
    expect(
      forbiddenAt([
        [5, 7, 1], [7, 7, 1],
        [6, 5, 1], [6, 6, 1],
        [6, 7, 1]
      ])
    ).toBe('double-three')
  })

  it('一真一假（假三被白棋封住成活四点）不构成三三', () => {
    // 横向三右端被白 (8,7) 封：无有效成活四点；纵向为真活三
    expect(
      forbiddenAt([
        [8, 7, 2], [5, 7, 1], [6, 7, 1],
        [7, 5, 1], [7, 6, 1],
        [7, 7, 1]
      ])
    ).toBeNull()
  })

  it('边线上的三（无法成活四）为假三', () => {
    // 横向 (0,7)(1,7)+p=(2,7) 贴边；纵向为真活三 → 只剩一个真三
    expect(
      forbiddenAt([
        [0, 7, 1], [1, 7, 1],
        [2, 5, 1], [2, 6, 1],
        [2, 7, 1]
      ])
    ).toBeNull()
  })

  it('成活四点本身是三三禁手点的三为假三（嵌套校验）', () => {
    // p=(7,7)：
    //  - 横向三 (5,7)(6,7)+p：成活四点只有 (4,7) 与 (8,7)；
    //    (8,7) 被白 (9,7) 封死；(4,7) 落黑会同时形成纵向三 (4,5)(4,6)(4,7)
    //    与斜向三 (2,5)(3,6)(4,7) → (4,7) 是三三禁手点 → 横向三为假三
    //  - 纵向三 (7,5)(7,6)+p：成活四点 (7,4) 合法 → 真三
    //  → 只有一个真三，p 不是禁手
    expect(
      forbiddenAt([
        [5, 7, 1], [6, 7, 1],
        [7, 5, 1], [7, 6, 1],
        [4, 5, 1], [4, 6, 1],
        [2, 5, 1], [3, 6, 1],
        [9, 7, 2],
        [7, 7, 1]
      ])
    ).toBeNull()
  })

  it('同上局面去掉封口的白子后，横向三复活 → 三三禁手', () => {
    expect(
      forbiddenAt([
        [5, 7, 1], [6, 7, 1],
        [7, 5, 1], [7, 6, 1],
        [4, 5, 1], [4, 6, 1],
        [2, 5, 1], [3, 6, 1],
        [7, 7, 1]
      ])
    ).toBe('double-three')
  })
})

describe('禁手判定：杂项', () => {
  it('无关白子不影响双三判定', () => {
    expect(
      forbiddenAt([
        [5, 7, 1], [6, 7, 1],
        [7, 5, 1], [7, 6, 1],
        [8, 8, 2],
        [7, 7, 1]
      ])
    ).toBe('double-three')
  })

  it('孤立落子无禁手', () => {
    expect(forbiddenAt([[7, 7, 1]])).toBeNull()
  })
})
